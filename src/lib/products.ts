export function getLocalizedProduct(product: Product, lang: "es" | "en"): Product {
  if (lang === "en" && product.en) {
    return {
      ...product,
      title: product.en.title ?? product.title,
      short: product.en.short ?? product.short,
      summary: product.en.summary ?? product.summary,
      why: product.en.why ?? product.why,
      special: product.en.special ?? product.special,
      includes: product.en.includes ?? product.includes,
      excludes: product.en.excludes ?? product.excludes,
      info: product.en.info ?? product.info,
      tips: product.en.tips ?? product.tips,
    };
  }
  return product;
}

export const getProduct = (slug: string, lang: "es" | "en" = "es") => {
  const p = PRODUCTS.find((item) => item.slug === slug);
  return p ? getLocalizedProduct(p, lang) : undefined;
};

export const getRelated = (product: Product, n = 3, lang: "es" | "en" = "es") =>
  PRODUCTS.filter((p) => p.category === product.category && p.slug !== product.slug)
    .slice(0, n)
    .map((p) => getLocalizedProduct(p, lang));

