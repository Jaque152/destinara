export const computeDiscount = (subtotal: number, code: string | null) => {
  if (!code) return 0;
  const c = COUPONS[code];
  if (!c) return 0;
  if (c.type === "percent") return Math.round(subtotal * (c.value / 100));
  return Math.min(c.value, subtotal);
};

